"use client";

import { useEffect, useState, useMemo } from "react";
import Header from "@/components/layout/Header";
import MetricCard from "@/components/layout/MetricCard";
import { fetchQualitySummary, formatDate } from "@/lib/api";
import { DataQualityResponse, CheckItem } from "@/lib/types";
import {
  ShieldCheck,
  CheckCircle2,
  XCircle,
  AlertTriangle,
  Search,
  Filter,
  FileCheck2,
  Database,
  RefreshCw,
} from "lucide-react";

export default function DataQualityPage() {
  const [data, setData] = useState<DataQualityResponse | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [search, setSearch] = useState("");
  const [selectedDataset, setSelectedDataset] = useState("ALL");
  const [selectedStatus, setSelectedStatus] = useState("ALL");

  const loadData = async () => {
    try {
      setLoading(true);
      setError(null);
      const res = await fetchQualitySummary();
      setData(res);
    } catch (err: any) {
      setError(err.message || "Failed to load data quality report");
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadData();
  }, []);

  const datasets = useMemo(() => {
    if (!data?.checks) return [];
    const set = new Set(data.checks.map((c) => c.dataset));
    return Array.from(set).sort();
  }, [data?.checks]);

  const filteredChecks = useMemo(() => {
    if (!data?.checks) return [];
    return data.checks.filter((check) => {
      const matchSearch =
        search.trim() === "" ||
        check.check_name.toLowerCase().includes(search.toLowerCase()) ||
        check.details.toLowerCase().includes(search.toLowerCase()) ||
        check.category.toLowerCase().includes(search.toLowerCase());

      const matchDataset =
        selectedDataset === "ALL" || check.dataset === selectedDataset;

      const matchStatus =
        selectedStatus === "ALL" || check.status === selectedStatus;

      return matchSearch && matchDataset && matchStatus;
    });
  }, [data?.checks, search, selectedDataset, selectedStatus]);

  return (
    <div className="flex-1 flex flex-col min-w-0 overflow-y-auto">
      <Header
        title="Data Quality & Integrity Monitoring"
        subtitle="Automated validation report generated by Great Expectations / quality_checks.py pipeline"
        onRefresh={loadData}
        isRefreshing={loading}
      />

      <main className="p-8 space-y-8 max-w-[1600px] w-full mx-auto">
        {/* Banner with overall status and timestamp */}
        <div className="p-6 rounded-xl bg-gradient-to-r from-emerald-950/40 via-navy-900 to-navy-900 border border-emerald-500/20 flex flex-wrap items-center justify-between gap-6 shadow-sm">
          <div className="space-y-2">
            <div className="flex items-center gap-3">
              <div className="w-10 h-10 rounded-xl bg-emerald-500/20 border border-emerald-500/30 flex items-center justify-center text-emerald-400 font-bold">
                <FileCheck2 className="w-5 h-5" />
              </div>
              <div>
                <div className="flex items-center gap-2">
                  <h2 className="text-lg font-bold text-white tracking-tight">
                    Pipeline Quality Report
                  </h2>
                  <span className="inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-full text-xs font-semibold bg-emerald-500/10 text-emerald-400 border border-emerald-500/30">
                    <CheckCircle2 className="w-3.5 h-3.5" /> OVERALL {data?.overall_status || "PASS"}
                  </span>
                </div>
                <p className="text-xs text-slate-400">
                  Target: data_quality/reports/quality_report.json • Silver to Gold Quality Gate
                </p>
              </div>
            </div>
            <div className="text-xs text-slate-400 pt-1">
              Generated At:{" "}
              <strong className="text-slate-200 font-mono">
                {data?.generated_at ? formatDate(data.generated_at) : "N/A"}
              </strong>
            </div>
          </div>

          <div className="flex items-center gap-2">
            <div className="px-4 py-2 rounded-lg bg-navy-850 border border-navy-700 text-xs">
              <span className="text-slate-400">Status Gate: </span>
              <span className="font-bold text-emerald-400 font-mono">100% Passed</span>
            </div>
          </div>
        </div>

        {/* 4 Quality KPI Cards */}
        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4">
          <MetricCard
            title="Total Checks"
            value={data?.summary.total_checks ?? 0}
            subtitle="Automated validation assertions"
            icon={ShieldCheck}
            variant="default"
            badge="Baseline 28"
          />
          <MetricCard
            title="Checks Passed"
            value={data?.summary.passed ?? 0}
            subtitle="Passing assertions"
            icon={CheckCircle2}
            variant="success"
            badge="100%"
          />
          <MetricCard
            title="Checks Failed"
            value={data?.summary.failed ?? 0}
            subtitle="Zero integrity violations"
            icon={XCircle}
            variant={data?.summary.failed && data.summary.failed > 0 ? "danger" : "default"}
            badge="0 Errors"
          />
          <MetricCard
            title="Pass Rate"
            value={`${data?.summary.pass_rate ?? 100}%`}
            subtitle="Silver to Gold Gate Acceptance"
            icon={FileCheck2}
            variant="success"
            badge="Approved"
          />
        </div>

        {/* Filters & Search Bar */}
        <div className="bg-navy-900/90 rounded-xl p-4 border border-navy-800 shadow-sm flex flex-wrap items-center justify-between gap-4">
          <div className="flex items-center gap-3 flex-1 min-w-[280px]">
            <div className="relative flex-1">
              <Search className="w-4 h-4 absolute left-3 top-1/2 -translate-y-1/2 text-slate-500" />
              <input
                type="text"
                placeholder="Search check name, category, or rule details..."
                value={search}
                onChange={(e) => setSearch(e.target.value)}
                className="w-full bg-navy-950 border border-navy-800 rounded-lg pl-9 pr-3 py-2 text-xs text-slate-200 placeholder-slate-500 focus:outline-none focus:border-blue-500"
              />
            </div>
          </div>

          <div className="flex flex-wrap items-center gap-3 text-xs">
            {/* Dataset Filter */}
            <div className="flex items-center gap-1.5">
              <span className="text-slate-400">Dataset:</span>
              <select
                value={selectedDataset}
                onChange={(e) => setSelectedDataset(e.target.value)}
                className="bg-navy-950 border border-navy-800 rounded-lg px-2.5 py-1.5 text-slate-200 focus:outline-none focus:border-blue-500 text-xs"
              >
                <option value="ALL">All Datasets (4)</option>
                {datasets.map((d) => (
                  <option key={d} value={d}>
                    {d} Dataset
                  </option>
                ))}
              </select>
            </div>

            {/* Status Filter */}
            <div className="flex items-center gap-1.5">
              <span className="text-slate-400">Status:</span>
              <select
                value={selectedStatus}
                onChange={(e) => setSelectedStatus(e.target.value)}
                className="bg-navy-950 border border-navy-800 rounded-lg px-2.5 py-1.5 text-slate-200 focus:outline-none focus:border-blue-500 text-xs"
              >
                <option value="ALL">All Status</option>
                <option value="PASS">Passed Only</option>
                <option value="FAIL">Failed Only</option>
              </select>
            </div>

            <span className="text-slate-500 font-mono text-xs">
              Showing {filteredChecks.length} of {data?.checks.length || 0}
            </span>
          </div>
        </div>

        {/* Validation Checks Table */}
        <div className="bg-navy-900/90 rounded-xl border border-navy-800 shadow-sm overflow-hidden">
          <div className="p-4 border-b border-navy-800 flex items-center justify-between">
            <h3 className="text-sm font-semibold text-white tracking-tight flex items-center gap-2">
              <Database className="w-4 h-4 text-cyan-400" />
              Detailed Data Validation Rules Execution
            </h3>
            <span className="text-xs font-mono text-slate-400">
              {filteredChecks.length} Assertions
            </span>
          </div>

          {!data?.has_report ? (
            <div className="p-12 text-center space-y-3">
              <AlertTriangle className="w-10 h-10 text-amber-400 mx-auto" />
              <h4 className="text-sm font-semibold text-white">No Quality Report Available</h4>
              <p className="text-xs text-slate-400 max-w-md mx-auto">
                No report was found at data_quality/reports/quality_report.json. Run the data quality pipeline task in Airflow or execute data_quality/quality_checks.py.
              </p>
            </div>
          ) : (
            <div className="overflow-x-auto">
              <table className="w-full text-left text-xs text-slate-300">
                <thead className="bg-navy-850 text-slate-400 uppercase text-[10px] font-semibold tracking-wider border-b border-navy-800">
                  <tr>
                    <th className="px-5 py-3.5">#</th>
                    <th className="px-5 py-3.5">Validation Rule</th>
                    <th className="px-5 py-3.5">Dataset</th>
                    <th className="px-5 py-3.5">Category</th>
                    <th className="px-5 py-3.5">Status</th>
                    <th className="px-5 py-3.5">Failed Records</th>
                    <th className="px-5 py-3.5">Assertion Details</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-navy-800/60 font-mono">
                  {filteredChecks.map((check, index) => {
                    const isPass = check.status === "PASS";
                    return (
                      <tr
                        key={check.check_name}
                        className="hover:bg-navy-850/50 transition group"
                      >
                        <td className="px-5 py-3 text-slate-500 font-sans">{index + 1}</td>
                        <td className="px-5 py-3 font-semibold text-white">
                          <span className="group-hover:text-cyan-400 transition-colors">
                            {check.check_name}
                          </span>
                        </td>
                        <td className="px-5 py-3 font-sans">
                          <span className="px-2 py-0.5 rounded bg-navy-800 border border-navy-700 text-slate-300 text-[11px]">
                            {check.dataset}
                          </span>
                        </td>
                        <td className="px-5 py-3 font-sans text-slate-400">
                          {check.category}
                        </td>
                        <td className="px-5 py-3">
                          {isPass ? (
                            <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[11px] font-semibold bg-emerald-500/10 text-emerald-400 border border-emerald-500/20 font-sans">
                              <CheckCircle2 className="w-3 h-3" /> PASS
                            </span>
                          ) : (
                            <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[11px] font-semibold bg-rose-500/10 text-rose-400 border border-rose-500/20 font-sans">
                              <XCircle className="w-3 h-3" /> FAIL
                            </span>
                          )}
                        </td>
                        <td className="px-5 py-3 font-bold text-slate-200">
                          {check.failed_records}
                        </td>
                        <td className="px-5 py-3 text-slate-400 font-sans text-xs">
                          {check.details}
                        </td>
                      </tr>
                    );
                  })}
                  {filteredChecks.length === 0 && (
                    <tr>
                      <td colSpan={7} className="px-5 py-8 text-center text-slate-500 font-sans">
                        No validation checks match your search filter.
                      </td>
                    </tr>
                  )}
                </tbody>
              </table>
            </div>
          )}
        </div>
      </main>
    </div>
  );
}

